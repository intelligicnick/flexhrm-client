export type SupervisorTranslationKey = keyof typeof translations.en;

export function getSupervisorLang(): SupervisorLang {
  const stored = localStorage.getItem(STORAGE_KEY);
  return stored === "hi" ? "hi" : "en";
}

export function setSupervisorLang(lang: SupervisorLang): void {
  localStorage.setItem(STORAGE_KEY, lang);
}

export function t(key: SupervisorTranslationKey, lang?: SupervisorLang): string {
  const l = lang || getSupervisorLang();
  const val = translations[l][key];
  if (typeof val === "string") return val;
  return String(val);
}

export function tStatus(status: string, lang?: SupervisorLang): string {
  const l = lang || getSupervisorLang();
  const map = translations[l].visitStatus as Record<string, string>;
  return map[status] || status;
}

export { translations };
