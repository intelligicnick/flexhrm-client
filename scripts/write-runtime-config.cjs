/**
 * Writes dist/runtime-config.js from PUBLIC_API_URL so static Hostinger deploys
 * call the NestJS API instead of same-origin /api (which returns 404 on static hosting).
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
require('dotenv').config({ path: path.join(root, '.env.production') });
require('dotenv').config({ path: path.join(root, '.env') });

const distDir = path.join(root, 'dist');
let apiBase = (process.env.PUBLIC_API_URL || '').trim().replace(/\/$/, '');

if (!apiBase) {
  const publicConfig = path.join(root, 'public', 'runtime-config.js');
  if (fs.existsSync(publicConfig)) {
    const match = fs
      .readFileSync(publicConfig, 'utf8')
      .match(/__FLEXHRM_API_BASE__\s*=\s*"([^"]*)"/);
    if (match) {
      apiBase = match[1].trim();
    }
  }
}

fs.mkdirSync(distDir, { recursive: true });
fs.writeFileSync(
  path.join(distDir, 'runtime-config.js'),
  [
    '// Generated by npm run build from PUBLIC_API_URL.',
    '// Empty string = browser calls same-origin /api (Node proxy or reverse proxy required).',
    `window.__FLEXHRM_API_BASE__ = ${JSON.stringify(apiBase)};`,
    '',
  ].join('\n'),
);

if (apiBase) {
  console.log(`Wrote dist/runtime-config.js (API base: ${apiBase})`);
} else {
  console.warn(
    'PUBLIC_API_URL is not set — dist/runtime-config.js uses same-origin /api. ' +
      'Copy .env.production.example to .env.production before building for static Hostinger deploys.',
  );
}
